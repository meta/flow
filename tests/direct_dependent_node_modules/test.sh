printf "\nFocus a file in node_modules with a dependent also in node_modules.\n"
assert_ok "$FLOW" force-recheck --focus node_modules/a.js

printf "\nBy focusing on a.js, we should force-check main.js, and only report\n"
printf "errors there, not in node_modules.\n"
assert_errors "$FLOW" status --show-lazy-status --no-auto-start

printf "\nChange the type of x in a.js. main.js sees it through b.js, also in\n"
printf "node_modules, so b.js has to be merged again.\n"
printf "// @flow\n\nexport const x = 'x';\n" > node_modules/a.js
assert_ok "$FLOW" force-recheck --no-auto-start node_modules/a.js
assert_errors "$FLOW" status --show-lazy-status --no-auto-start
