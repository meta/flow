# pnpm links each package from its store into the node_modules of every package that depends on
# it, and links workspace packages into each other's node_modules. The crawl reports each file
# once, by its real path, including one also reached through a file symlink, and doesn't walk every
# path through the cycles between the packages.

export LC_ALL=C

# Links $2 to the directory $1, which is relative to the directory containing $2. On Windows,
# MSYS and Cygwin create a native symlink rather than a copy.
link_dir() {
  mkdir -p "$(dirname "$2")"
  MSYS=winsymlinks:nativestrict CYGWIN=winsymlinks:nativestrict ln -s "$1" "$2"
}

link_dir .pnpm/dep@1.0.0/node_modules/dep node_modules/dep
link_dir ../../../node_modules/.pnpm/dep@1.0.0/node_modules/dep packages/a/node_modules/dep
link_dir ../../../node_modules/.pnpm/dep@1.0.0/node_modules/dep packages/b/node_modules/dep
link_dir ../../b packages/a/node_modules/b
link_dir ../../c packages/a/node_modules/c
link_dir ../../a packages/b/node_modules/a
link_dir ../../c packages/b/node_modules/c
link_dir ../../a packages/c/node_modules/a
link_dir ../../b packages/c/node_modules/b
MSYS=winsymlinks:nativestrict CYGWIN=winsymlinks:nativestrict ln -s ../../node_modules/dep/index.js packages/a/dep.js

assert_ok "$FLOW" ls --strip-root | sort
