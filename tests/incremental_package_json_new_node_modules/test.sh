printf "\nInitial state:\n"
assert_errors "$FLOW" status --no-auto-start .

printf "\nInstall b into a new sub/node_modules:\n"
mkdir -p sub/node_modules/b
echo "export const v: string = '';" > sub/node_modules/b/lib.js
echo '{"name": "b", "main": "lib.js"}' > sub/node_modules/b/package.json
assert_ok "$FLOW" force-recheck --no-auto-start \
  sub/node_modules/b/lib.js sub/node_modules/b/package.json
assert_ok "$FLOW" status --no-auto-start .
