# Workspace packages linked into each other's node_modules, as pnpm links them, form symlink
# cycles. The crawl must terminate, list each file once by its real path, and still resolve
# modules through the links.

export LC_ALL=C

if command -v cmd.exe > /dev/null 2>&1; then
  rm -rf \
    node_modules/.pnpm/dep@1.0.0/node_modules/peer \
    node_modules/.pnpm/node_modules/a \
    node_modules/.pnpm/node_modules/b \
    node_modules/.pnpm/peer@1.0.0/node_modules/dep \
    packages/a/node_modules/b \
    packages/a/node_modules/dep \
    packages/a/node_modules/ext \
    packages/b/node_modules/a \
    packages/b/node_modules/ext \
    ../external/ext/node_modules/ext2 \
    ../external/ext2/node_modules/ext
  cmd.exe /D /S /C 'mklink /D node_modules\.pnpm\dep@1.0.0\node_modules\peer ..\..\peer@1.0.0\node_modules\peer' > /dev/null
  cmd.exe /D /S /C 'mklink /D node_modules\.pnpm\node_modules\a ..\..\..\packages\a' > /dev/null
  cmd.exe /D /S /C 'mklink /D node_modules\.pnpm\node_modules\b ..\..\..\packages\b' > /dev/null
  cmd.exe /D /S /C 'mklink /D node_modules\.pnpm\peer@1.0.0\node_modules\dep ..\..\dep@1.0.0\node_modules\dep' > /dev/null
  cmd.exe /D /S /C 'mklink /D packages\a\node_modules\b ..\..\b' > /dev/null
  cmd.exe /D /S /C 'mklink /D packages\a\node_modules\dep ..\..\..\node_modules\.pnpm\dep@1.0.0\node_modules\dep' > /dev/null
  cmd.exe /D /S /C 'mklink /D packages\a\node_modules\ext ..\..\..\..\external\ext' > /dev/null
  cmd.exe /D /S /C 'mklink /D packages\b\node_modules\a ..\..\a' > /dev/null
  cmd.exe /D /S /C 'mklink /D packages\b\node_modules\ext ..\..\..\..\external\ext' > /dev/null
  cmd.exe /D /S /C 'mklink /D ..\external\ext\node_modules\ext2 ..\..\ext2' > /dev/null
  cmd.exe /D /S /C 'mklink /D ..\external\ext2\node_modules\ext ..\..\ext' > /dev/null
fi

printf "flow ls lists each file once:\n"
assert_ok "$FLOW" ls --strip-root | sort

printf "\nflow ls of a package lists its links' targets once:\n"
assert_ok "$FLOW" ls --strip-root packages/a | sort

printf "\nflow check resolves modules through the links:\n"
assert_errors "$FLOW" check --strip-root .

printf "\nflow status resolves modules through the links:\n"
assert_errors "$FLOW" status --strip-root .
assert_ok "$FLOW" stop .
