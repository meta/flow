# pnpm links workspace packages into each other's node_modules, and links store packages to their
# dependencies, which form symlink cycles. The crawl must terminate, list each file once by its
# real path, and still resolve modules through the links.

export LC_ALL=C

# Links $2 to the directory $1, which is relative to the directory containing $2. On Windows,
# MSYS and Cygwin create a native symlink rather than a copy.
link_dir() {
  mkdir -p "$(dirname "$2")"
  MSYS=winsymlinks:nativestrict CYGWIN=winsymlinks:nativestrict ln -s "$1" "$2"
}

link_dir ../../b packages/a/node_modules/b
link_dir ../../a packages/b/node_modules/a
link_dir ../../../node_modules/.pnpm/dep@1.0.0/node_modules/dep packages/a/node_modules/dep
link_dir ../../peer@1.0.0/node_modules/peer node_modules/.pnpm/dep@1.0.0/node_modules/peer
link_dir ../../dep@1.0.0/node_modules/dep node_modules/.pnpm/peer@1.0.0/node_modules/dep
link_dir ../../../packages/a node_modules/.pnpm/node_modules/a
link_dir ../../../packages/b node_modules/.pnpm/node_modules/b

printf "flow ls lists each file once:\n"
assert_ok "$FLOW" ls --strip-root | sort

printf "\nflow check resolves modules through the links:\n"
assert_errors "$FLOW" check --strip-root .
